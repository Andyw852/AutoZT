def build_docx(version):
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.enum.table import WD_TABLE_ALIGNMENT
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Inches, Pt

    def run(p, text, size, bold=False, italic=False, style=""):
        r = p.add_run(text)
        r.bold, r.italic = bold, italic
        r.font.size = Pt(size - 0.5 if style == "c" else size)
        r.font.name = "Consolas" if style == "c" else "Times New Roman"
        r.font.subscript = True if style == "s" else None
        r._element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "SimSun")

    def styled(p, text, size, bold=False, italic=False, cell=None):
        for t, st in runs(text, cell):
            run(p, t, size, bold, italic, st)

    def insert_ordered(parent, child, successors):
        """Insert child before the first successor present (OOXML child order is schema-checked)."""
        for name in successors:
            nxt = parent.find(qn("w:" + name))
            if nxt is not None:
                nxt.addprevious(child)
                return
        parent.append(child)

    def border_el(tag, edges):
        b = OxmlElement(tag)
        for edge, (val, sz) in edges.items():
            e = OxmlElement("w:" + edge)
            for k, v in (("val", val), ("sz", str(sz)), ("space", "0"), ("color", "000000")):
                e.set(qn("w:" + k), v)
            b.append(e)
        return b

    def fill(cell, width, text, size, bold=False, italic=False, key=None, center=False):
        cell.width = Inches(width)
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.0
        if center:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        styled(p, text, size, bold, italic, key)

    def paragraph(doc, space_before, space_after, page_break=False):
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(space_before)
        p.paragraph_format.space_after = Pt(space_after)
        p.paragraph_format.page_break_before = page_break
        return p

    doc = Document()
    props = doc.core_properties
    props.title, props.author, props.last_modified_by = "AutoZT skill tables", "AutoZT", "AutoZT"
    props.created = props.modified = DOC_DATE
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = Inches(11), Inches(8.5)
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Inches(0.65))
    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(9)
    normal.element.get_or_add_rPr().rFonts.set(qn("w:eastAsia"), "SimSun")

    size = 8.5
    for n, (key, title, head, widths, rows, note, grouped) in enumerate(TABLES):
        label, _, rest = title.partition(" | ")
        p = paragraph(doc, 4, 4, page_break=n > 0)
        run(p, label + " | ", 10.5, bold=True)
        styled(p, rest, 10.5)

        t = doc.add_table(rows=1, cols=len(head))
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        t.autofit = False
        for col, w in zip(t.columns, widths):   # w:gridCol; LibreOffice and Google Docs read these
            col.width = Inches(w)
        tblPr = t._tbl.tblPr
        insert_ordered(tblPr, border_el("w:tblBorders", {
            "top": ("single", 12), "left": ("nil", 0), "bottom": ("single", 12), "right": ("nil", 0),
            "insideH": ("nil", 0), "insideV": ("nil", 0)}),
            ("shd", "tblLayout", "tblCellMar", "tblLook", "tblCaption", "tblDescription"))
        mar = OxmlElement("w:tblCellMar")
        for side, v in (("top", 50), ("left", 70), ("bottom", 50), ("right", 70)):
            e = OxmlElement("w:" + side)
            e.set(qn("w:w"), str(v))
            e.set(qn("w:type"), "dxa")
            mar.append(e)
        insert_ordered(tblPr, mar, ("tblLook", "tblCaption", "tblDescription"))
        repeat = OxmlElement("w:tblHeader")
        repeat.set(qn("w:val"), "true")
        t.rows[0]._tr.get_or_add_trPr().append(repeat)
        twod = head.index("2D") if "2D" in head else -1

        for j, h in enumerate(head):
            c = t.rows[0].cells[j]
            fill(c, widths[j], h, size, bold=True, center=j == twod)
            insert_ordered(c._tc.get_or_add_tcPr(), border_el("w:tcBorders", {"bottom": ("single", 8)}),
                           ("shd", "noWrap", "tcMar", "textDirection", "tcFitText", "vAlign", "hideMark"))
        for stage, r in table_rows(rows, grouped):
            if stage:
                cells = t.add_row().cells
                fill(cells[0].merge(cells[-1]), sum(widths), stage, size, bold=True, italic=True)
            cells = t.add_row().cells
            for j, val in enumerate(r):
                fill(cells[j], widths[j], val, size, key=(key, j), center=j == twod)

        p = paragraph(doc, 3, 0)
        run(p, "Notes: ", 8, bold=True)
        styled(p, note.format(version=version), 8)
    doc.save(OUT_DOCX)


