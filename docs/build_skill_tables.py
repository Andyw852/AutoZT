def split_skills(cell):
    return [s.strip() for s in cell.split("/")]


def core_skills():
    return [s for r in t1_rows() for s in split_skills(r[0])]


def table_rows(rows, grouped):
    """Yield (stage or None, row) in display order; stage is set on the first row of a group."""
    for stage, srows in (rows if grouped else [(None, rows)]):
        for i, r in enumerate(srows):
            yield (stage if i == 0 else None), r


