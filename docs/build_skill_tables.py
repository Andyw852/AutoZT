def check_repo():
    errors = []
    skills = core_skills()
    if len(skills) != 20 or len(set(skills)) != 20:
        errors.append(f"Table 1 must list 20 distinct skills, got {len(skills)}")
    if len(t1_rows()) != 17:
        errors.append(f"T1_NOTE says 17 rows, Table 1 has {len(t1_rows())}")

    on_disk = {p.parent.name for p in (REPO / "skill").glob("*/skill.yaml") if not p.parent.name.startswith("_")}
    listed = set(skills) | {r[0] for r in S1}
    if on_disk != listed:
        errors.append(f"skill/ out of sync: missing={sorted(on_disk - listed)} unknown={sorted(listed - on_disk)}")
    for r in S1:
        m = re.search(r'^version:\s*"?([\d.]+)', (REPO / "skill" / r[0] / "skill.yaml").read_text(), re.M)
        if not m or not r[-1].startswith(m.group(1) + ";"):
            errors.append(f"S1 version of {r[0]} differs from skill.yaml ({m and m.group(1)})")

    sys.path.insert(0, str(REPO))
    from autozt.mcp import TOOLS
    tiers = Counter(t[3] for t in TOOLS)
    for tier, risk in (("Read", "read"), ("Mutate", "mutate"), ("Destructive", "destructive")):
        row = next(r for r in T3 if r[0].startswith(tier))
        if row[0] != f"{tier} ({tiers[risk]})":
            errors.append(f"Table 3 says '{row[0]}', autozt/mcp.py has {tiers[risk]} {risk} tools")
    if f"({len(TOOLS)} tools)" not in T3_NOTE or f"all {len(TOOLS)}" not in T3_NOTE:
        errors.append(f"T3_NOTE tool total differs from autozt/mcp.py ({len(TOOLS)})")
    unknown_tools = tool_names() - {t[0] for t in TOOLS}
    if unknown_tools:
        errors.append(f"Table 3 names unknown MCP tools: {sorted(unknown_tools)}")

    # Every engine named in Table 1 / Table S1 must list that skill in Table S2.
    users = {}
    for names, _, used_by in S2:
        expanded = set()
        for u in re.split(r",| and ", re.sub(r"\(.*?\)", "", used_by)):
            u = u.strip()
            if u == "most skills":
                expanded |= on_disk
            elif u.endswith("*"):
                expanded |= {s for s in on_disk if s.startswith(u[:-1])}
            else:
                expanded.add(u)
        for name in re.sub(r"\(.*?\)", "", names).split(","):
            users[name.strip().lower()] = expanded
    for r in t1_rows() + S1:
        engines = re.sub(r"optional|reads|outputs|interface reserved|VASP WAVECAR", " ", r[4])
        for eng in re.split(r"[,;()/]", engines):
            eng = eng.strip().lower()
            for skill in split_skills(r[0]) if eng in users else []:
                if skill not in users[eng]:
                    errors.append(f"Table S2 '{eng}' does not list {skill}")

    for key, _, _, widths, rows, note, grouped in TABLES:
        if sum(widths) > TEXT_WIDTH_IN + 1e-9:
            errors.append(f"{key}: column widths {sum(widths):.2f} in exceed {TEXT_WIDTH_IN} in")
        for text in [note] + [c for _, r in table_rows(rows, grouped) for c in r]:
            for path in re.findall(PATH_RE, text):
                if not (REPO / path).exists():
                    errors.append(f"{key}: path does not exist: {path}")
    if errors:
        sys.exit("[ERROR] " + "\n[ERROR] ".join(errors))


def main():
    check_repo()
    version = re.search(r'^version\s*=\s*"([^"]+)"', (REPO / "pyproject.toml").read_text(), re.M).group(1)
    build_md(version)
    build_html(version)
    build_docx(version)
    for p in (OUT_DOCX, OUT_MD, OUT_HTML):
        print(p)


if __name__ == "__main__":
    main()
