def build_html(version):
    out = [HTML_HEAD, f'    <p class="subtitle">{html_cell(SUBTITLE)}</p>\n']
    for key, title, head, _, rows, note, grouped in TABLES:
        out.append(f'    <h2>{html_cell(title)}</h2>\n    <div class="wrap"><table>\n')
        out.append("      <thead><tr>" + "".join(f"<th>{html.escape(h)}</th>" for h in head)
                   + "</tr></thead>\n      <tbody>\n")
        for stage, r in table_rows(rows, grouped):
            if stage:
                out.append(f'        <tr class="stage"><td colspan="{len(head)}">{html.escape(stage)}</td></tr>\n')
            out.append("        <tr>" + "".join(f"<td>{html_cell(c, (key, j))}</td>" for j, c in enumerate(r))
                       + "</tr>\n")
        out.append("      </tbody>\n    </table></div>\n")
        out.append(f'    <p class="note"><strong>Notes:</strong> {html_cell(note.format(version=version))}</p>\n')
    out.append("  </main>\n</body>\n</html>\n")
    OUT_HTML.write_text("".join(out), encoding="utf-8")


