PATH_RE = r"(?:skill|autozt|docs)/[\w./-]*[\w/]"
SUB_RE = re.compile(r"(?<=[κTEk])_(L|e|F|z)(?![A-Za-z])")
CODE_WORDS = {"phonon-*", "phonon-mlff-*", "kl-mlff-*", "opt-mlff-*", "approval_mode: tty", "max_jobs",
              "force=true", "AUTOZT_MCP_PROFILE=full", "LAYER_THICKNESS", "FIT_ENGINE",
              "VACUUM_AXIS_POLICY", "KTEMP_MODE"}


def tool_names():
    names = set()
    for r in T3:
        names |= {t.strip(" .…") for t in re.split(r"[,;]", r[2])}
    return {n.split()[-1] for n in names if n}   # 'full profile also prepare_step' -> 'prepare_step'


@functools.lru_cache(maxsize=None)
def identifier_re(one_word_tools):
    tools = tool_names()
    if not one_word_tools:
        tools = {t for t in tools if "_" in t}
    names = set(core_skills()) | {r[0] for r in S1} | tools | CODE_WORDS
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    return re.compile(rf"(?<![\w*/-])(?:{PATH_RE}|{alt})(?![\w-])")


def runs(text, cell=None):
    out = []

    def plain(t):
        pos = 0
        for m in SUB_RE.finditer(t):
            out.extend([(t[pos:m.start()], ""), (m.group(1), "s")])
            pos = m.end()
        out.append((t[pos:], ""))

    if cell == CLI_CELL:
        for i, cmd in enumerate(text.split("; ")):
            out += [("; ", ""), (cmd, "c")] if i else [(cmd, "c")]
        return out
    pos = 0
    for m in identifier_re(cell == TOOLS_CELL).finditer(text):
        plain(text[pos:m.start()])
        out.append((m.group(0), "c"))
        pos = m.end()
    plain(text[pos:])
    return [(t, st) for t, st in out if t]


def md_cell(text, cell=None, in_table=True):
    out = []
    for t, st in runs(text, cell):
        if in_table:
            t = t.replace("|", "\\|")
        out.append(f"`{t}`" if st == "c" else f"<sub>{t}</sub>" if st == "s" else t)
    return "".join(out)


def html_cell(text, cell=None):
    tags = {"c": "code", "s": "sub"}
    return "".join(f"<{tags[st]}>{html.escape(t)}</{tags[st]}>" if st else html.escape(t)
                   for t, st in runs(text, cell))


# --------------------------------------------------------------------------------------
# Markdown
# --------------------------------------------------------------------------------------

def build_md(version):
    lines = ["# AutoZT skill tables", "", md_cell(SUBTITLE, in_table=False), ""]
    for key, title, head, _, rows, note, grouped in TABLES:
        cols = (["Stage"] + head) if grouped else head
        lines += [f"## {md_cell(title, in_table=False)}", "",
                  "| " + " | ".join(cols) + " |", "|" + "|".join([":--"] * len(cols)) + "|"]
        for stage, r in table_rows(rows, grouped):
            cells = [md_cell(c, (key, j)) for j, c in enumerate(r)]
            if grouped:
                cells.insert(0, stage or "")
            lines.append("| " + " | ".join(cells) + " |")
        lines += ["", f"*Notes:* {md_cell(note.format(version=version), in_table=False)}", ""]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")


